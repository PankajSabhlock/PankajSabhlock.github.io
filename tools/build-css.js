#!/usr/bin/env node
/*
  Joins the site's stylesheets into one file (site.css) so the home page makes one CSS request, not five.
  The order is the order index.html used to load them, so the cascade is unchanged.

  Edit the source files, then run from the repository root:   node tools/build-css.js
*/
'use strict';
process.on('uncaughtException', err => {
  console.error('build-css failed: ' + err.message);
  process.exit(1);
});
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCES = ['styles.css', 'certs.css', 'motion.css', 'projects.css', 'theme.css'];

const parts = SOURCES.map(name => {
  const css = fs.readFileSync(path.join(ROOT, name), 'utf8').replace(/\r\n/g, '\n').replace(/^﻿/, '').trimEnd();
  return '/* ==== ' + name + ' ==== */\n' + css + '\n';
});
const header = '/* GENERATED by tools/build-css.js. Edit ' + SOURCES.join(', ') + ' and rebuild; do not edit this file. */\n';
fs.writeFileSync(path.join(ROOT, 'site.css'), header + parts.join('\n'));
console.log('Built site.css from ' + SOURCES.length + ' files');
